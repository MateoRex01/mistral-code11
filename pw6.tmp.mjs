import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('pageerror', e => errs.push((e.stack || e.message).split('\n').slice(0, 3).join(' | ')));
page.on('console', m => { if (m.type() === 'error' && !/favicon|WebGL/.test(m.text())) errs.push('console: ' + m.text()); });
await page.goto('file:///workspace/github__MateoRex01__mistral-code11/mekanika.html');
await page.waitForTimeout(2200);
await page.click('#menuRoot button[data-m="sandbox"]');
await page.waitForTimeout(400);
await page.click('.subpanel .map-picker .mp');
await page.waitForTimeout(7000);
console.log('sandbox:', JSON.stringify(await page.evaluate(() => ({ hud: document.getElementById('hudRoot')?.children.length || 0, mm: !!document.getElementById('minimap') }))));
await page.keyboard.press('KeyB');
await page.waitForTimeout(700);
console.log('builder:', JSON.stringify(await page.evaluate(() => ({ open: !!document.getElementById('b-name'), tools: document.querySelectorAll('#buildRoot .tool').length, parts: document.querySelectorAll('#buildRoot .plist > *').length }))));
const box = await page.locator('#gameCanvas').boundingBox();
await page.mouse.click(box.x + box.width / 2, box.y + box.height * .62);
await page.waitForTimeout(250);
await page.mouse.click(box.x + box.width / 2 + 40, box.y + box.height * .62);
await page.waitForTimeout(250);
await page.keyboard.press('Control+z');
await page.waitForTimeout(300);
console.log('colocados y deshecho');
await page.click('#b-test');
await page.waitForTimeout(3500);
console.log('tras Test:', JSON.stringify(await page.evaluate(() => ({ vname: document.getElementById('vname')?.textContent, hud: document.getElementById('hudRoot')?.innerHTML.length || 0 }))));
await page.screenshot({ path: '/tmp/e2e.png' });
console.log('ERRORES:', errs.length);
errs.slice(0, 8).forEach(e => console.log('—', e));
await browser.close();
